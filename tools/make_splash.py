#!/usr/bin/env python3
"""SuperCalc.OG splash converter: PNG -> SCS1 splash asset.

Usage (POSIX, Python 3 + Pillow):
  tools/make_splash.py SPLASH.png                       # regenerate firmware/frozen/sc_splash_data.py
  tools/make_splash.py SPLASH.png --sd splash.scs       # also write an SD card file
  tools/make_splash.py SPLASH.png --preview out.png     # also render what the PicoCalc will show
  tools/make_splash.py --check splash.scs --preview p.png   # decode an existing .scs file

The PicoCalc display runs LofiFren's 4-bit (16 colour, LUT) framebuffer, so the image is
reduced to 16 colours (Pillow MAXCOVERAGE + k-means, no dithering: on this artwork
dithering doubled the size and did not lower the visible error), snapped to RGB565.

SCS1 format (little-endian; also what /sd/splash.scs must contain):
  off size
   0   4   magic b"SCS1"
   4   2   width  (must be 320)
   6   2   height (must be 320)
   8   1   bits per pixel (must be 4)
   9   1   encoding: 0 = raw, 1 = zlib (zlib header window <= 1 KB, wbits 8..10)
  10   1   palette entries N (1..16)
  11   1   reserved, 0
  12  2*N  palette, RGB565 big-endian (the byte order the display wants)
  ..   ..  pixels: 320 rows x 160 bytes, 2 pixels per byte, LEFT pixel in the HIGH
           nibble (framebuf.GS4_HMSB); raw = exactly 51200 bytes, zlib = one zlib
           stream that inflates to exactly those 51200 bytes.
"""
import argparse
import os
import struct
import sys
import zlib

W = H = 320
ROW = W // 2
WBITS = 10          # 1 KB inflate window on the device
MAGIC = b"SCS1"


def to565(c):
    r, g, b = c
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def from565(v):
    r, g, b = (v >> 11) & 31, (v >> 5) & 63, v & 31
    return ((r << 3) | (r >> 2), (g << 2) | (g >> 4), (b << 3) | (b >> 2))


def quantize(png):
    from PIL import Image
    im = Image.open(png)
    if im.size != (W, H):
        sys.exit("splash must be %dx%d, got %dx%d" % (W, H, im.width, im.height))
    if im.mode in ("RGBA", "LA", "P"):
        im = im.convert("RGBA")
        bg = Image.new("RGBA", im.size, (0, 0, 0, 255))   # flatten on black
        bg.alpha_composite(im)
        im = bg
    rgb = im.convert("RGB")
    q = rgb.quantize(16, method=Image.Quantize.MAXCOVERAGE, kmeans=50)
    raw = q.getpalette()[:48]
    pal565 = []
    for i in range(16):
        v = to565(tuple(raw[3 * i:3 * i + 3]))
        if v not in pal565:
            pal565.append(v)
    pal = [from565(v) for v in pal565]
    # exact nearest-colour remap against the snapped palette (no dither)
    cache = {}
    src = rgb.tobytes()
    idx = bytearray(W * H)
    for i in range(W * H):
        c = src[3 * i:3 * i + 3]
        j = cache.get(c)
        if j is None:
            r, g, b = c
            j = min(range(len(pal)), key=lambda k: (pal[k][0] - r) ** 2 + (pal[k][1] - g) ** 2 + (pal[k][2] - b) ** 2)
            cache[c] = j
        idx[i] = j
    packed = bytes((idx[i] << 4) | idx[i + 1] for i in range(0, W * H, 2))
    return pal565, packed, src


def encode(pal565, packed, enc=1):
    hdr = MAGIC + struct.pack("<HHBBBB", W, H, 4, enc, len(pal565), 0)
    hdr += b"".join(struct.pack(">H", v) for v in pal565)
    if enc == 1:
        c = zlib.compressobj(9, zlib.DEFLATED, WBITS)
        body = c.compress(packed) + c.flush()
    else:
        body = packed
    return hdr + body


def decode(blob):
    """Reference decoder (same rules as firmware/frozen/sc_splash.py)."""
    if blob[:4] != MAGIC:
        raise ValueError("bad magic")
    w, h, bpp, enc, n, _ = struct.unpack("<HHBBBB", blob[4:12])
    if (w, h, bpp) != (W, H, 4) or not 1 <= n <= 16 or enc not in (0, 1):
        raise ValueError("unsupported header")
    pal = [struct.unpack(">H", blob[12 + 2 * i:14 + 2 * i])[0] for i in range(n)]
    body = blob[12 + 2 * n:]
    if enc == 1:
        if (body[0] >> 4) + 8 > WBITS:
            raise ValueError("zlib window too large")
        packed = zlib.decompress(body)
    else:
        packed = body
    if len(packed) != ROW * H:
        raise ValueError("pixel data is %d bytes, need %d" % (len(packed), ROW * H))
    return pal, packed


def preview(pal, packed, path):
    from PIL import Image
    out = bytearray()
    for b in packed:
        for k in (b >> 4, b & 15):
            out += bytes(from565(pal[k]) if k < len(pal) else (0, 0, 0))
    Image.frombytes("RGB", (W, H), bytes(out)).save(path)


def write_frozen(blob, path, src_name):
    lines = ["# GENERATED by tools/make_splash.py from %s -- do not edit." % src_name,
             "# SCS1 splash asset (%d bytes). Frozen into the firmware, so DATA lives in" % len(blob),
             "# XIP flash; sc_splash reads it through a zero-copy io.BytesIO.",
             "DATA = ("]
    for i in range(0, len(blob), 32):
        lines.append("    %r" % blob[i:i + 32])
    lines.append(")")
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        f.write("\n".join(lines) + "\n")
    os.replace(tmp, path)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("png", nargs="?")
    ap.add_argument("--frozen", default=os.path.join(here, "..", "firmware", "frozen", "sc_splash_data.py"),
                    help="frozen asset module to write (default: firmware/frozen/sc_splash_data.py)")
    ap.add_argument("--no-frozen", action="store_true", help="do not write the frozen module")
    ap.add_argument("--sd", help="also write an SD card .scs file here (copy it to /sd/splash.scs)")
    ap.add_argument("--sd-raw", action="store_true", help="SD file uncompressed (encoding 0, 51244 bytes)")
    ap.add_argument("--preview", help="write a PNG of exactly what the display will show")
    ap.add_argument("--check", help="decode an existing .scs file instead of converting")
    a = ap.parse_args()

    if a.check:
        with open(a.check, "rb") as f:
            pal, packed = decode(f.read())
        print("OK: %s, %d colours" % (a.check, len(pal)))
        if a.preview:
            preview(pal, packed, a.preview)
        return
    if not a.png:
        ap.error("need a PNG (or --check FILE)")
    pal565, packed, src = quantize(a.png)
    blob = encode(pal565, packed, 1)
    pal, back = decode(blob)
    assert back == packed and pal == pal565
    # error report vs the source (after flattening), in 8-bit RGB units
    se = mx = 0
    for i in range(W * H):
        k = (packed[i >> 1] >> 4) if not i & 1 else (packed[i >> 1] & 15)
        c = from565(pal565[k])
        for j in range(3):
            d = c[j] - src[3 * i + j]
            se += d * d
            mx = max(mx, abs(d))
    rmse = (se / (W * H * 3)) ** 0.5
    print("palette: %d colours; asset: %d bytes (zlib, wbits %d); RMSE vs PNG %.2f, max %d"
          % (len(pal565), len(blob), WBITS, rmse, mx))
    if not a.no_frozen:
        write_frozen(blob, os.path.normpath(a.frozen), os.path.basename(a.png))
        print("wrote", os.path.normpath(a.frozen))
    if a.sd:
        with open(a.sd, "wb") as f:
            f.write(encode(pal565, packed, 0) if a.sd_raw else blob)
        print("wrote", a.sd)
    if a.preview:
        preview(pal565, packed, a.preview)
        print("wrote", a.preview)


if __name__ == "__main__":
    main()
